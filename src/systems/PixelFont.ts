export interface TextMetrics {
  width: number;
  height: number;
}

export class PixelFont {
  static measure(text: string, scale: number): TextMetrics {
    const chars = Math.max(text.length, 1);
    return {
      width: chars * GLYPH_WIDTH * scale + (chars - 1) * GLYPH_SPACING * scale,
      height: GLYPH_HEIGHT * scale,
    };
  }

  static text(
    scene: Phaser.Scene,
    text: string,
    color: number,
    scale = 1,
    x = 0,
    y = 0,
  ): Phaser.GameObjects.Image {
    const key = PixelFont.buildTexture(scene, text, color, scale);
    return scene.add.image(x, y, key);
  }

  private static buildTexture(scene: Phaser.Scene, text: string, color: number, scale: number): string {
    const key = `pixel-font:${text}:${color.toString(16)}:${scale}`;

    if (scene.textures.exists(key)) {
      return key;
    }

    const upper = text.toUpperCase();
    const metrics = PixelFont.measure(upper, scale);
    const canvasTexture = scene.textures.createCanvas(key, Math.max(metrics.width, 1), metrics.height);

    if (!canvasTexture) {
      throw new Error(`PixelFont: failed to create texture "${key}".`);
    }

    const ctx = canvasTexture.getContext();
    ctx.fillStyle = toCss(color);

    for (let i = 0; i < upper.length; i++) {
      const glyph = GLYPHS[upper[i]] ?? GLYPHS['?'];
      const originX = i * (GLYPH_WIDTH + GLYPH_SPACING) * scale;

      for (let row = 0; row < GLYPH_HEIGHT; row++) {
        const line = glyph[row];
        for (let col = 0; col < GLYPH_WIDTH; col++) {
          if (line[col] === '#') {
            ctx.fillRect(originX + col * scale, row * scale, scale, scale);
          }
        }
      }
    }

    canvasTexture.refresh();
    return key;
  }
}
